// Spike F: privacy register = structured data in KVS (source of truth) + generated Confluence page (human-readable view).
// Idempotency: each decision has a decisionId; a processed-marker key prevents double application on retries.
// Concurrency: Confluence PUT uses version n+1; on 409 we refetch and retry once. Manual edits detected by version drift.
import api, { route } from '@forge/api';
import { kvs } from '@forge/kvs';
import { escapeXml, fingerprint } from './text';

export const REGISTER_STATUSES = ['PROPOSED', 'APPROVED', 'APPROVED_WITH_CONDITIONS', 'REJECTED', 'SUPERSEDED'];
const ENTRIES = 'register:entries';
const PAGE = 'register:page';

export async function applyDecision({ decisionId, issueKey, activity, status, conditions = [], categories = [], vendors = [], accountId, supersedes }) {
  if (!REGISTER_STATUSES.includes(status)) throw new Error('bad status');
  const marker = `register:decision:${decisionId}`;
  if (await kvs.get(marker)) return { applied: false, reason: 'duplicate decisionId (idempotent no-op)' };

  const entries = (await kvs.get(ENTRIES)) ?? {};
  const now = new Date().toISOString();
  if (supersedes && entries[supersedes]) entries[supersedes] = { ...entries[supersedes], status: 'SUPERSEDED', supersededBy: decisionId, updatedAt: now };
  const prev = entries[issueKey];
  entries[issueKey] = {
    issueKey, activity, status, conditions, categories, vendors,
    decisionId, decidedBy: accountId, updatedAt: now,
    history: [...(prev?.history ?? []), { decisionId, status, at: now, by: accountId }].slice(-20),
  };
  // NOTE: kvs.transact could make marker+entries atomic; spike uses sequential writes and records this as a gap.
  await kvs.set(ENTRIES, entries);
  await kvs.set(marker, { at: now });
  return { applied: true, entry: entries[issueKey] };
}

function renderStorage(entries, siteUrl) {
  const rows = Object.values(entries).sort((a, b) => a.issueKey.localeCompare(b.issueKey)).map((e) => `
    <tr><td><a href="${escapeXml(siteUrl)}/browse/${escapeXml(e.issueKey)}">${escapeXml(e.issueKey)}</a></td>
    <td>${escapeXml(e.activity)}</td><td><strong>${escapeXml(e.status)}</strong></td>
    <td>${escapeXml(e.categories.join(', '))}</td><td>${escapeXml(e.vendors.join(', '))}</td>
    <td>${escapeXml(e.conditions.join('; '))}</td><td>${escapeXml(e.decisionId)}</td><td>${escapeXml(e.updatedAt)}</td></tr>`).join('');
  return `<p><em>Generated by Article25 spike. Source of truth: app register. SYNTHETIC DATA.</em></p>
  <table><tbody><tr><th>Work item</th><th>Processing activity</th><th>Status</th><th>Data categories</th><th>Vendors</th><th>Conditions</th><th>Decision</th><th>Updated</th></tr>${rows}</tbody></table>`;
}

export async function publish({ spaceId, title = 'Article25 Privacy Register (SPIKE)', siteUrl = '' }) {
  const entries = (await kvs.get(ENTRIES)) ?? {};
  const body = renderStorage(entries, siteUrl);
  const hash = fingerprint(body.replace(/\d{4}-\d{2}-\d{2}T[\d:.]+Z/g, ''));
  let page = await kvs.get(PAGE);
  if (page?.contentHash === hash) return { published: false, reason: 'no content change (idempotent)', page };

  let adopted = null;
  if (!page?.pageId) {
    const res = await api.asApp().requestConfluence(route`/wiki/api/v2/pages`, {
      method: 'POST', headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ spaceId, status: 'current', title, body: { representation: 'storage', value: body } }),
    });
    const json = await res.json();
    if (res.ok) {
      const rec = { pageId: json.id, spaceId, lastVersion: json.version?.number, contentHash: hash };
      await kvs.set(PAGE, rec);
      return { published: true, created: true, page: rec, url: json._links?.webui };
    }
    // Duplicate title: the page exists but this installation has no pointer to it (reinstall, other installation, lost state).
    // Adopt it by exact title lookup in the space, then fall through to the update path.
    if (res.status !== 400) return { published: false, status: res.status, error: json };
    const found = await api.asApp().requestConfluence(route`/wiki/api/v2/pages?space-id=${spaceId}&title=${title}&status=current`);
    const fj = await found.json();
    const existing = fj.results?.[0];
    if (!existing) return { published: false, status: res.status, error: json, adoptLookup: found.status };
    adopted = { pageId: existing.id, versionAtAdoption: existing.version?.number };
    page = { pageId: existing.id, spaceId, lastVersion: null, contentHash: null };
  }

  for (let attempt = 0; attempt < 2; attempt++) {
    const cur = await api.asApp().requestConfluence(route`/wiki/api/v2/pages/${page.pageId}`);
    const curJson = await cur.json();
    if (!cur.ok) return { published: false, status: cur.status, error: curJson };
    const currentVersion = curJson.version.number;
    const manualEditDetected = page.lastVersion != null && currentVersion !== page.lastVersion;
    const res = await api.asApp().requestConfluence(route`/wiki/api/v2/pages/${page.pageId}`, {
      method: 'PUT', headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ id: page.pageId, status: 'current', title, body: { representation: 'storage', value: body }, version: { number: currentVersion + 1, message: 'Article25 register update' } }),
    });
    if (res.status === 409 && attempt === 0) continue;
    const json = await res.json();
    if (!res.ok) return { published: false, status: res.status, error: json };
    const rec = { ...page, lastVersion: json.version.number, contentHash: hash };
    await kvs.set(PAGE, rec);
    return { published: true, created: false, adopted, manualEditDetected, fromVersion: currentVersion, toVersion: json.version.number, page: rec };
  }
  return { published: false, reason: 'version conflict after retry' };
}

export const getRegister = async () => ({ entries: (await kvs.get(ENTRIES)) ?? {}, page: (await kvs.get(PAGE)) ?? null });
